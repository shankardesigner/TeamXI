def realistic_batting_predictor_dynamic(
    player_id, opponent_team, venue, match_type, batting_position
):
    """
    Realistic integer runs prediction with DYNAMIC data-driven factors
    """
    print(f"\n MAKING PREDICTION FOR {player_id}")
    print("=" * 50)

    # Get player data
    player_df = df_enhanced[df_enhanced["player_id"] == player_id].sort_values("date")
    if player_df.empty:
        return f" Player {player_id} not found in dataset."

    # Get player profile
    player_profile = player_profiles[player_profiles["player_id"] == player_id]
    if len(player_profile) == 0:
        player_type = " UNKNOWN PLAYER"
        avg_runs = player_df["runs_scored"].mean() if len(player_df) > 0 else 20
    else:
        player_type = player_profile["player_type"].iloc[0]
        avg_runs = player_profile["avg_runs"].iloc[0]
        player_name = player_profile["name"].iloc[0]

    # Get venue effect
    venue_effect = venue_effects[venue_effects["venue"] == venue]
    if len(venue_effect) == 0:
        venue_factor = 1.0
        venue_type = " NEUTRAL (Unknown)"
    else:
        venue_factor = venue_effect["final_venue_factor"].iloc[0]
        venue_type = venue_effect["venue_type"].iloc[0]

    # Player stats
    player_recent = (
        player_df["runs_scored"].tail(10).mean() if len(player_df) > 0 else avg_runs
    )
    player_sr = player_df["strike_rate"].mean() if len(player_df) > 0 else 120

    # Base prediction from player's capability
    base_prediction = max(avg_runs, player_recent)

    # === BATTER QUALITY BONUS ===
    quality_bonus = 0.0
    if "WORLD-CLASS" in player_type:
        quality_bonus = 8.0
    elif "SOLID" in player_type or "RELIABLE" in player_type:
        quality_bonus = 4.0
    elif "DEPENDABLE" in player_type:
        quality_bonus = 2.0
    elif "HARD-HITTING" in player_type:
        quality_bonus = 3.0

    base_prediction += quality_bonus

    # === OPPONENT BOWLING STRENGTH ===
    # Get opponent bowling strength from the data
    opponent_strength_data = batting_df[batting_df["opponent_team"] == opponent_team]
    if len(opponent_strength_data) > 0:
        opponent_strength = opponent_strength_data["bowling_strength_norm"].mean()
    else:
        opponent_strength = 0.5  # Default neutral

    # Convert bowling strength to factor (0-1  factor)
    opponent_factor = 1.0 + (0.5 - opponent_strength)  # Higher strength = lower factor

    # Categorize opponent
    if opponent_strength > 0.7:
        opponent_type = " ELITE BOWLING"
        opponent_factor *= 0.8
    elif opponent_strength > 0.6:
        opponent_type = " STRONG BOWLING"
        opponent_factor *= 0.9
    elif opponent_strength < 0.4:
        opponent_type = " WEAK BOWLING"
        opponent_factor *= 1.2
    elif opponent_strength < 0.3:
        opponent_type = " VERY WEAK BOWLING"
        opponent_factor *= 1.4
    else:
        opponent_type = " MEDIUM BOWLING"

    # === BATTING POSITION EFFECT ===
    if batting_position <= 2:  # Openers
        position_factor = 1.3
        position_type = " OPENING BATTER"
    elif batting_position <= 4:  # Top order
        position_factor = 1.2
        position_type = " TOP ORDER"
    elif batting_position <= 6:  # Middle order
        position_factor = 1.0
        position_type = " MIDDLE ORDER"
    else:  # Lower order
        position_factor = 0.7
        position_type = " LOWER ORDER"

    # === FORM EFFECT ===
    if len(player_df) >= 5:
        recent_5 = player_df["runs_scored"].tail(5).mean()
        recent_15 = (
            player_df["runs_scored"].tail(15).mean()
            if len(player_df) >= 15
            else recent_5
        )
        recent_form = recent_5 - recent_15
    else:
        recent_form = 0

    if recent_form > 15:
        form_factor = 1.3
        form_type = " EXCELLENT FORM"
    elif recent_form > 8:
        form_factor = 1.15
        form_type = " GOOD FORM"
    elif recent_form < -15:
        form_factor = 0.7
        form_type = " POOR FORM"
    elif recent_form < -8:
        form_factor = 0.85
        form_type = " BELOW AVERAGE"
    else:
        form_factor = 1.0
        form_type = " NORMAL FORM"

    # === CALCULATE REALISTIC INTEGER PREDICTION ===
    realistic_float = (
        base_prediction * opponent_factor * venue_factor * position_factor * form_factor
    )

    # Convert to integer with realistic cricket logic
    if realistic_float >= 80:
        runs_predicted = int(realistic_float)  # Big score - keep exact
    elif realistic_float >= 50:
        runs_predicted = int(round(realistic_float / 5) * 5)  # Round to nearest 5
    elif realistic_float >= 25:
        runs_predicted = int(round(realistic_float / 2) * 2)  # Round to nearest 2
    else:
        runs_predicted = int(round(realistic_float))  # Round normally

    # Ensure realistic constraints
    if batting_position >= 7 and runs_predicted > 35:  # Lower order limit
        runs_predicted = min(35, runs_predicted)

    if "WORLD-CLASS" in player_type and runs_predicted < 20:  # Elite batter floor
        runs_predicted = max(20, runs_predicted)

    # Display prediction
    player_display_name = player_name if "player_name" in locals() else player_id
    print(f" Player: {player_display_name} ({player_type})")
    print(f" vs {opponent_team} ({opponent_type})")
    print(f" {venue} ({venue_type})")
    print(f" {match_type} | Batting: {batting_position} ({position_type})")
    print(f" {form_type}")
    print(f" Base: {base_prediction:.1f} (incl. {quality_bonus:+} quality bonus)")
    print(
        f" Multipliers: Opponent {opponent_factor:.2f}x | Venue {venue_factor:.2f}x"
    )
    print(f"   Position {position_factor:.2f}x | Form {form_factor:.2f}x")
    print(f" Raw: {realistic_float:.1f}  FINAL: {runs_predicted} runs")

    # Performance rating
    if runs_predicted >= 75:
        print(f"    CENTURY CONTENDER! ")
    elif runs_predicted >= 50:
        print(f"    Half-century likely! ")
    elif runs_predicted >= 35:
        print(f"    Good contribution! ")
    elif runs_predicted >= 20:
        print(f"    Decent innings! ")
    elif runs_predicted >= 10:
        print(f"     Modest contribution! ")
    else:
        print(f"    Low score expected ")

    print("=" * 50)
    return runs_predicted



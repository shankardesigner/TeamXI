def add_icc_team_rankings(df, odi_rankings, t20_rankings):
    """
    Add ICC team rankings as features based on match type
    """
    print(" Adding ICC team rankings...")

    # Create ranking dictionaries
    odi_ranking_dict = dict(zip(t20_rankings['Team'], t20_rankings['rating']))
    t20_ranking_dict = dict(zip(odi_rankings['Team'], odi_rankings['rating']))

    # Add batting team ranking
    df['batting_team_rating'] = df.apply(
        lambda x: odi_ranking_dict[x['batting_team']] if x['match_type'] == 'ODI'
        else t20_ranking_dict.get(x['batting_team'], 100),  # Default 100 if not found
        axis=1
    )

    # Add opponent team ranking
    df['opponent_team_rating'] = df.apply(
        lambda x: odi_ranking_dict[x['opponent_team']] if x['match_type'] == 'ODI'
        else t20_ranking_dict.get(x['opponent_team'], 100),
        axis=1
    )

    # Calculate team strength advantage
    df['team_strength_advantage'] = df['batting_team_rating'] - df['opponent_team_rating']

    # Normalize ratings (0-1 scale)
    max_rating = max(df['batting_team_rating'].max(), df['opponent_team_rating'].max())
    df['batting_team_strength'] = df['batting_team_rating'] / max_rating
    df['opponent_team_strength'] = df['opponent_team_rating'] / max_rating

    print(f" Added ICC rankings for {len(df['batting_team'].unique())} teams")
    return df


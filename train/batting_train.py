def calculate_dynamic_venue_effects(df):
    """
    Dynamically calculate venue effects from historical data
    """
    print(" Calculating dynamic venue effects...")

    venue_stats = (
        df.groupby("venue")
        .agg(
            {
                "runs_scored": ["mean", "std", "count"],
                "strike_rate": "mean",
                "boundaries": "mean",
                "sixes": "mean",
            }
        )
        .round(2)
    )

    venue_stats.columns = [
        "venue_avg_runs",
        "venue_std_runs",
        "match_count",
        "venue_avg_sr",
        "venue_avg_boundaries",
        "venue_avg_sixes",
    ]
    venue_stats = venue_stats.reset_index()

    # Calculate venue factor (compared to overall average)
    overall_avg_runs = df["runs_scored"].mean()
    venue_stats["venue_factor"] = venue_stats["venue_avg_runs"] / overall_avg_runs

    # Categorize venues based on runs scored
    def categorize_venue(row):
        if row["match_count"] < 5:  # Not enough data
            return " NEUTRAL", 1.0

        if row["venue_avg_runs"] >= overall_avg_runs * 1.15:
            return " BATTER'S PARADISE", 1.3
        elif row["venue_avg_runs"] >= overall_avg_runs * 1.05:
            return " HIGH-SCORING", 1.15
        elif row["venue_avg_runs"] <= overall_avg_runs * 0.85:
            return " BOWLER FRIENDLY", 0.8
        elif row["venue_avg_runs"] <= overall_avg_runs * 0.95:
            return " BALANCED", 0.9
        else:
            return " NEUTRAL", 1.0

    venue_stats[["venue_type", "venue_factor_cat"]] = venue_stats.apply(
        lambda x: pd.Series(categorize_venue(x)), axis=1
    )

    # Use a blend of calculated and categorical factors
    venue_stats["final_venue_factor"] = (
        venue_stats["venue_factor"] + venue_stats["venue_factor_cat"]
    ) / 2

    return venue_stats[["venue", "venue_avg_runs", "venue_type", "final_venue_factor"]]


def create_dynamic_player_profiles(df):
    """
    Create dynamic player profiles from historical data
    """
    print(" Creating dynamic player profiles...")

    player_profiles = (
        df.groupby("player_id")
        .agg(
            {
                "player_name": "first",
                "runs_scored": ["mean", "max", "std", "count"],
                "strike_rate": "mean",
                "batting_position": ["mean", "min", "max"],
                "boundaries": "mean",
                "sixes": "mean",
                "balls_faced": "mean",
            }
        )
        .round(2)
    )

    player_profiles.columns = [
        "name",
        "avg_runs",
        "max_runs",
        "std_runs",
        "matches_played",
        "avg_strike_rate",
        "avg_position",
        "min_position",
        "max_position",
        "avg_boundaries",
        "avg_sixes",
        "avg_balls_faced",
    ]
    player_profiles = player_profiles.reset_index()

    # Categorize players dynamically
    def categorize_player(row):
        avg_runs = row["avg_runs"]
        position = row["avg_position"]
        strike_rate = row["avg_strike_rate"]
        matches = row["matches_played"]

        if matches < 5:  # Not enough data
            return " NEW PLAYER"

        if avg_runs > 45 and position <= 3:
            return " WORLD-CLASS TOP ORDER"
        elif avg_runs > 35 and position <= 3:
            return " SOLID TOP ORDER"
        elif avg_runs > 30 and position <= 4:
            return " RELIABLE TOP/MIDDLE"
        elif avg_runs > 25 and position <= 6:
            return " DEPENDABLE MIDDLE ORDER"
        elif avg_runs > 20:
            return " USEFUL MIDDLE/LOWER"
        elif strike_rate > 140:
            return " HARD-HITTING FINISHER"
        elif position >= 7:
            return " BOWLING ALL-ROUNDER"
        else:
            return " UTILITY PLAYER"

    player_profiles["player_type"] = player_profiles.apply(categorize_player, axis=1)

    return player_profiles



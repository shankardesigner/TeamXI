def calculate_opponent_bowling_strength(bowling_df, batting_df):
    """
    Calculate comprehensive opponent bowling strength using bowling data
    """
    print(" Calculating opponent bowling strength...")

    # Ensure date is datetime
    bowling_df = bowling_df.copy()
    bowling_df["date"] = pd.to_datetime(bowling_df["date"])
    bowling_df = bowling_df.sort_values(["opponent_team", "date"])

    # Calculate match-level bowling stats for each team
    match_bowling_stats = (
        bowling_df.groupby(["opponent_team", "date", "match_id", "venue"])
        .agg(
            {
                "runs_conceded": "sum",
                "balls_bowled": "sum",
                "wickets_taken": "sum",
                "dot_balls": "sum",
                "overs_bowled": "sum",
            }
        )
        .reset_index()
    )

    # Calculate derived metrics
    match_bowling_stats["economy_rate"] = (
        match_bowling_stats["runs_conceded"] / match_bowling_stats["overs_bowled"]
    ).fillna(6.0)
    match_bowling_stats["wickets_per_match"] = match_bowling_stats["wickets_taken"]
    match_bowling_stats["dot_ball_pct"] = (
        match_bowling_stats["dot_balls"] / match_bowling_stats["balls_bowled"] * 100
    ).fillna(25.0)

    # Calculate rolling averages for recent form (last 5 matches)
    match_bowling_stats["opponent_economy_last_5"] = match_bowling_stats.groupby(
        "opponent_team"
    )["economy_rate"].transform(lambda x: x.rolling(5, min_periods=1).mean())
    match_bowling_stats["opponent_wickets_last_5"] = match_bowling_stats.groupby(
        "opponent_team"
    )["wickets_per_match"].transform(lambda x: x.rolling(5, min_periods=1).mean())
    match_bowling_stats["opponent_dot_pct_last_5"] = match_bowling_stats.groupby(
        "opponent_team"
    )["dot_ball_pct"].transform(lambda x: x.rolling(5, min_periods=1).mean())

    # Venue-specific bowling performance
    venue_bowling_stats = (
        match_bowling_stats.groupby(["opponent_team", "venue"])
        .agg(
            {
                "economy_rate": "mean",
                "wickets_per_match": "mean",
                "dot_ball_pct": "mean",
            }
        )
        .reset_index()
    )
    venue_bowling_stats.columns = [
        "opponent_team",
        "venue",
        "venue_opponent_economy",
        "venue_opponent_wickets",
        "venue_opponent_dot_pct",
    ]

    # Merge venue stats back
    match_bowling_stats = match_bowling_stats.merge(
        venue_bowling_stats, on=["opponent_team", "venue"], how="left"
    )

    # Fill NaN venue stats with overall averages
    overall_avg_economy = match_bowling_stats["economy_rate"].mean()
    overall_avg_wickets = match_bowling_stats["wickets_per_match"].mean()
    overall_avg_dot_pct = match_bowling_stats["dot_ball_pct"].mean()

    match_bowling_stats["venue_opponent_economy"] = match_bowling_stats[
        "venue_opponent_economy"
    ].fillna(overall_avg_economy)
    match_bowling_stats["venue_opponent_wickets"] = match_bowling_stats[
        "venue_opponent_wickets"
    ].fillna(overall_avg_wickets)
    match_bowling_stats["venue_opponent_dot_pct"] = match_bowling_stats[
        "venue_opponent_dot_pct"
    ].fillna(overall_avg_dot_pct)

    # Create composite bowling strength score (lower economy = better bowling)
    match_bowling_stats["bowling_strength_composite"] = (
        (1 - (match_bowling_stats["opponent_economy_last_5"] / 12))
        * 0.4  # Economy component (40%)
        + (match_bowling_stats["opponent_wickets_last_5"] / 10)
        * 0.3  # Wicket component (30%)
        + (match_bowling_stats["opponent_dot_pct_last_5"] / 50)
        * 0.3  # Dot ball component (30%)
    )

    # Normalize to 0-1 scale
    min_strength = match_bowling_stats["bowling_strength_composite"].min()
    max_strength = match_bowling_stats["bowling_strength_composite"].max()
    match_bowling_stats["bowling_strength_norm"] = (
        match_bowling_stats["bowling_strength_composite"] - min_strength
    ) / (max_strength - min_strength + 1e-6)

    # Prepare for merging with batting data
    bowling_strength_features = match_bowling_stats[
        [
            "opponent_team",
            "date",
            "match_id",
            "venue",
            "opponent_economy_last_5",
            "opponent_wickets_last_5",
            "opponent_dot_pct_last_5",
            "venue_opponent_economy",
            "venue_opponent_wickets",
            "venue_opponent_dot_pct",
            "bowling_strength_norm",
        ]
    ]

    return bowling_strength_features



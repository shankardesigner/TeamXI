def safe_convert_season(x):
    try:
        return int(str(x).split("/")[0])
    except Exception:
        return 2023


def create_batting_features(
    df: pd.DataFrame, bowling_strength_df: pd.DataFrame
) -> pd.DataFrame:
    df = df.copy()
    df = df.sort_values(["player_id", "date"])

    print(" Creating enhanced batting features...")

    # Merge bowling strength features
    df["date"] = pd.to_datetime(df["date"])
    df = df.merge(
        bowling_strength_df,
        on=["opponent_team", "date", "match_id", "venue"],
        how="left",
    )

    # Fill any missing bowling strength with median
    if "bowling_strength_norm" in df.columns:
        df["bowling_strength_norm"] = df["bowling_strength_norm"].fillna(
            df["bowling_strength_norm"].median()
        )

    # --- Enhanced lagged features with more windows ---
    df["runs_avg_5_lagged"] = df.groupby("player_id")["runs_scored"].transform(
        lambda x: x.shift(1).rolling(5, min_periods=1).mean()
    )
    df["runs_avg_10_lagged"] = df.groupby("player_id")["runs_scored"].transform(
        lambda x: x.shift(1).rolling(10, min_periods=1).mean()
    )
    df["runs_avg_15_lagged"] = df.groupby("player_id")["runs_scored"].transform(
        lambda x: x.shift(1).rolling(15, min_periods=1).mean()
    )

    # Strike rate features
    df["sr_avg_5_lagged"] = df.groupby("player_id")["strike_rate"].transform(
        lambda x: x.shift(1).rolling(5, min_periods=1).mean()
    )
    df["sr_avg_10_lagged"] = df.groupby("player_id")["strike_rate"].transform(
        lambda x: x.shift(1).rolling(10, min_periods=1).mean()
    )

    # Boundary hitting ability
    df["boundaries_per_ball"] = (df["boundaries"] + df["sixes"]) / df["balls_faced"]
    df["boundaries_per_ball"] = df["boundaries_per_ball"].fillna(0)
    df["boundary_rate_5_lagged"] = df.groupby("player_id")[
        "boundaries_per_ball"
    ].transform(lambda x: x.shift(1).rolling(5, min_periods=1).mean())

    # Dismissal rate (if dismissed)
    if "dismissals" in df.columns:
        df["dismissal_rate"] = df["dismissals"]
        df["dismissal_rate_5_lagged"] = df.groupby("player_id")[
            "dismissal_rate"
        ].transform(lambda x: x.shift(1).rolling(5, min_periods=1).mean())

    # Phase-wise batting performance
    if all(
        col in df.columns for col in ["powerplay_runs", "middle_runs", "death_runs"]
    ):
        df["powerplay_avg"] = df["powerplay_runs"] / (df["powerplay_balls"] + 1e-6)
        df["middle_avg"] = df["middle_runs"] / (df["middle_balls"] + 1e-6)
        df["death_avg"] = df["death_runs"] / (df["death_balls"] + 1e-6)

    # --- Enhanced vs_opponent features ---
    def safe_opponent_avg(group):
        return group.shift(1).rolling(10, min_periods=1).mean()

    df["vs_opponent_avg_10_lagged"] = df.groupby(["player_id", "opponent_team"])[
        "runs_scored"
    ].transform(safe_opponent_avg)

    # Fill NaN values with player's overall average
    player_avg = df.groupby("player_id")["runs_scored"].transform("mean")
    df["vs_opponent_avg_10_lagged"] = df["vs_opponent_avg_10_lagged"].fillna(player_avg)

    # --- Career expectation with multiple windows ---
    df["expected_runs_5"] = df.groupby("player_id")["runs_scored"].transform(
        lambda x: x.shift(1).rolling(5, min_periods=1).mean()
    )
    df["expected_runs_10"] = df.groupby("player_id")["runs_scored"].transform(
        lambda x: x.shift(1).rolling(10, min_periods=1).mean()
    )
    df["expected_runs_15"] = df.groupby("player_id")["runs_scored"].transform(
        lambda x: x.shift(1).rolling(15, min_periods=1).mean()
    )

    # --- Form metrics ---
    df["recent_form"] = df["runs_avg_5_lagged"] - df["runs_avg_15_lagged"]
    df["momentum"] = df.groupby("player_id")["runs_scored"].transform(
        lambda x: x.shift(1).rolling(3, min_periods=1).mean()
        - x.shift(1).rolling(10, min_periods=1).mean()
    )

    # --- Venue context with enhanced features ---
    venue_avg = (
        df.groupby("venue")["runs_scored"]
        .mean()
        .reset_index()
        .rename(columns={"runs_scored": "venue_avg_runs"})
    )
    df = df.merge(venue_avg, on="venue", how="left")

    # Player's performance at this venue
    venue_player_avg = (
        df.groupby(["player_id", "venue"])["runs_scored"]
        .mean()
        .reset_index()
        .rename(columns={"runs_scored": "player_venue_avg"})
    )
    df = df.merge(venue_player_avg, on=["player_id", "venue"], how="left")
    df["player_venue_avg"] = df["player_venue_avg"].fillna(df["runs_avg_10_lagged"])

    # --- Match context ---
    df["season_numeric"] = df["season"].apply(safe_convert_season)
    df["match_importance"] = df["match_type"].map({"T20": 1, "ODI": 2}).fillna(1)

    # Batting position impact
    position_avg = (
        df.groupby("batting_position")["runs_scored"]
        .mean()
        .reset_index()
        .rename(columns={"runs_scored": "position_avg_runs"})
    )
    df = df.merge(position_avg, on="batting_position", how="left")

    # Days since last match
    df["days_since_last"] = df.groupby("player_id")["date"].diff().dt.days
    df["days_since_last"] = df["days_since_last"].fillna(30)

    # --- Enhanced interactions ---
    df["form_bowling_combo"] = df["runs_avg_5_lagged"] * (
        1 - df["bowling_strength_norm"]
    )
    df["venue_bowling_combo"] = df["venue_avg_runs"] * (1 - df["bowling_strength_norm"])
    df["player_venue_advantage"] = df["player_venue_avg"] - df["venue_avg_runs"]
    df["position_bowling_combo"] = df["position_avg_runs"] * (
        1 - df["bowling_strength_norm"]
    )
    df["recent_vs_career"] = df["runs_avg_5_lagged"] - df["expected_runs_15"]

    return df


